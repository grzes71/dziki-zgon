#!/usr/bin/env python3
"""Automated Memory Integrity Validation for Dziki Zgon.

Validates memory.json generated by export_portal_data.py against:
1. Non-overlapping allocated runtime segments in Atari 64 KB memory space.
2. Disjoint free headroom regions and exact gap arithmetic (sum == headroom).
3. Clear distinction between safe free space and reserved alignment buffers.
4. Mathematical consistency with Atari 48 KB user space ($0000-$BFFF = 49,152 B).
5. Exact match of Zero Page allocations ($80-$FF) against zeropage.asm.
6. Provenance and SHA256 integrity of analyzed XEX binary against file on disk.

Exit 0 on validation pass, non-zero on any integrity failure.
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

# Add project root to path
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from scripts.export_portal_data import parse_zeropage_asm


def verify_memory_integrity(
    memory_json_path: Path,
    zeropage_asm_path: Path,
    xex_binary_path: Path | None = None,
    require_binary_match: bool = True,
) -> bool:
    print(f"=== Dziki Zgon Memory Integrity Validation ===")
    print(f"Report: {memory_json_path}")
    print(f"ZeroPage SSOT: {zeropage_asm_path}")

    if not memory_json_path.exists():
        print(f"ERROR: {memory_json_path} does not exist!", file=sys.stderr)
        return False

    with open(memory_json_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    errors: list[str] = []

    # 1. Architectural constants & limits
    total_ram = data.get("total_ram_bytes", 65536)
    total_mapped = data.get("total_mapped_bytes", 0)
    free_headroom = data.get("free_headroom_bytes", 0)
    safe_headroom = data.get("safe_free_headroom_bytes", 0)
    reserved_headroom = data.get("reserved_headroom_bytes", 0)
    user_ram_limit = 0xC000  # 49,152 bytes ($0000 - $BFFF)

    if total_mapped + free_headroom != user_ram_limit:
        errors.append(
            f"Arithmetic mismatch: total_mapped ({total_mapped}) + free_headroom ({free_headroom}) "
            f"= {total_mapped + free_headroom} != user_ram_limit ({user_ram_limit})"
        )

    if safe_headroom + reserved_headroom != free_headroom:
        errors.append(
            f"Headroom partition mismatch: safe_free ({safe_headroom}) + reserved ({reserved_headroom}) "
            f"= {safe_headroom + reserved_headroom} != free_headroom ({free_headroom})"
        )

    # 2. Check allocated segments for overlaps
    segments = data.get("segments", [])
    runtime_segments = [
        s for s in segments
        if "WOLNY RAM" not in s.get("area_type", "")
        and s.get("area_type") != "Zero Page"
        and not (s.get("start_hex") == "$2000" and s.get("end_hex") == "$2007")  # Transient load-time INI loader
    ]

    sorted_segs = sorted(runtime_segments, key=lambda s: int(s["start_hex"].lstrip("$"), 16))
    for i in range(len(sorted_segs) - 1):
        cur = sorted_segs[i]
        nxt = sorted_segs[i + 1]
        c_end = int(cur["end_hex"].lstrip("$"), 16)
        n_start = int(nxt["start_hex"].lstrip("$"), 16)
        if c_end >= n_start:
            errors.append(
                f"Allocated segment overlap: {cur['symbol']} ({cur['address_range']}) "
                f"collides with {nxt['symbol']} ({nxt['address_range']})"
            )

    # 3. Check free regions for overlaps and calculate sum
    free_regions = data.get("free_regions", [])
    sum_free_gaps = sum(r["size_bytes"] for r in free_regions)

    if sum_free_gaps != free_headroom:
        errors.append(
            f"Sum of free gaps ({sum_free_gaps}) does not match free_headroom_bytes ({free_headroom})"
        )

    sorted_free = sorted(free_regions, key=lambda r: int(r["start_hex"].lstrip("$"), 16))
    for i in range(len(sorted_free) - 1):
        cur = sorted_free[i]
        nxt = sorted_free[i + 1]
        c_end = int(cur["end_hex"].lstrip("$"), 16)
        n_start = int(nxt["start_hex"].lstrip("$"), 16)
        if c_end >= n_start:
            errors.append(
                f"Free regions overlap: {cur['address_range']} collides with {nxt['address_range']}"
            )

    # 4. Verify free regions do not overlap any allocated segments
    for fr in free_regions:
        f_s = int(fr["start_hex"].lstrip("$"), 16)
        f_e = int(fr["end_hex"].lstrip("$"), 16)

        # Check OS low memory $0000-$05FF
        if max(f_s, 0) <= min(f_e, 0x05FF):
            errors.append(f"Free region {fr['address_range']} collides with reserved OS RAM ($0000-$05FF)")

        # Check all runtime allocated segments
        for seg in runtime_segments:
            s_s = int(seg["start_hex"].lstrip("$"), 16)
            s_e = int(seg["end_hex"].lstrip("$"), 16)
            if max(f_s, s_s) <= min(f_e, s_e):
                errors.append(
                    f"Free region {fr['address_range']} collides with allocated segment "
                    f"{seg['symbol']} ({seg['address_range']})"
                )

    # 5. Verify Zero Page allocations against zeropage.asm
    zp_asm_entries = parse_zeropage_asm(zeropage_asm_path)
    zp_report_entries = data.get("zero_page", [])

    if len(zp_asm_entries) != len(zp_report_entries):
        errors.append(
            f"Zero Page count mismatch: zeropage.asm has {len(zp_asm_entries)} entries, "
            f"memory.json has {len(zp_report_entries)}"
        )
    else:
        for asm_e, rep_e in zip(zp_asm_entries, zp_report_entries):
            if asm_e["symbol"] != rep_e["symbol"]:
                errors.append(f"Zero Page symbol mismatch: {asm_e['symbol']} != {rep_e['symbol']}")
            if asm_e["start_hex"] != rep_e["start_hex"]:
                errors.append(f"Zero Page address mismatch for {asm_e['symbol']}: {asm_e['start_hex']} != {rep_e['start_hex']}")

    # Check Zero Page range bounds ($0080 - $00FF)
    for ze in zp_report_entries:
        s_val = int(ze["start_hex"].lstrip("$"), 16)
        e_val = int(ze["end_hex"].lstrip("$"), 16)
        if s_val < 0x80 or e_val > 0xFF:
            errors.append(f"Zero Page entry {ze['symbol']} ({ze['address_range']}) exceeds $0080-$00FF boundary")

    # 6. Verify Binary and Provenance
    provenance = data.get("binary_provenance", {})
    origin = provenance.get("origin", "unavailable")
    bin_info = data.get("binary")

    print(f"Binary Provenance Origin: {origin}")
    print(f"Source Commit SHA: {provenance.get('source_commit_sha')}")
    print(f"Binary SHA256: {provenance.get('binary_sha256')}")
    print(f"Built From Current Source: {provenance.get('built_from_current_source')}")

    # Check internal consistency within memory.json
    if bin_info and provenance:
        if bin_info.get("sha256") and provenance.get("binary_sha256"):
            if bin_info.get("sha256") != provenance.get("binary_sha256"):
                errors.append(
                    f"Internal provenance SHA256 mismatch within memory.json: binary.sha256 ({bin_info.get('sha256')}) "
                    f"!= provenance.binary_sha256 ({provenance.get('binary_sha256')})"
                )

    if xex_binary_path and xex_binary_path.is_file():
        actual_sha = hashlib.sha256(xex_binary_path.read_bytes()).hexdigest()
        if bin_info and bin_info.get("sha256") != actual_sha:
            msg = (
                f"Binary SHA256 mismatch: memory.json has {bin_info.get('sha256')}, "
                f"file {xex_binary_path.name} has {actual_sha}"
            )
            if require_binary_match:
                errors.append(msg)
            else:
                print(f"[WARN] {msg}", file=sys.stderr)
        if provenance.get("binary_sha256") and provenance.get("binary_sha256") != actual_sha:
            msg = (
                f"Provenance SHA256 mismatch: memory.json has {provenance.get('binary_sha256')}, "
                f"file {xex_binary_path.name} has {actual_sha}"
            )
            if require_binary_match:
                errors.append(msg)
            else:
                print(f"[WARN] {msg}", file=sys.stderr)

    # Results
    if errors:
        print("\n[FAIL] Memory integrity validation found errors:", file=sys.stderr)
        for err in errors:
            print(f"  - {err}", file=sys.stderr)
        return False

    print("\n[PASS] All memory integrity checks passed successfully:")
    print(f"  • Total Usable RAM: {user_ram_limit} B ($0000-$BFFF)")
    print(f"  • Non-overlapping Mapped Payload: {total_mapped} B")
    print(f"  • Total Free Headroom: {free_headroom} B")
    print(f"    - Safe Usable Free Space: {safe_headroom} B")
    print(f"    - Reserved Alignment Buffers: {reserved_headroom} B")
    print(f"  • Verified Zero Page Entries: {len(zp_report_entries)} (Strictly within $80-$FF)")
    print(f"  • Binary Segments Analyzed: {len(bin_info['segments']) if bin_info else 0}")
    return True


def main() -> None:
    root = PROJECT_ROOT
    mem_json = root / "reports" / "portal" / "memory.json"
    zp_asm = root / "zeropage.asm"
    xex_bin = root / "dziki_zgon.xex"

    success = verify_memory_integrity(mem_json, zp_asm, xex_bin)
    sys.exit(0 if success else 1)


if __name__ == "__main__":
    main()

